// Voice packs written by the site: a narrator's test pack from their own uploads (GET /api/studio/pack). The files
// match what pipeline/lore/voicepack.py writes for the same recordings: render_toc and render_clips are ported line
// for line, and site/tests/fixtures/ pins both sides (site/tests/voicepack.test.mjs, pipeline test_voicepack.py).

import { planPack, packFolder } from "../public/voices/testpack.js";
import { zipStream, zipLength } from "./zip.js";

// ## Interface of addon/LoreForever/LoreForever.toc (a test checks they match). If it falls behind, the pack still
// loads with "Load out of date AddOns" ticked.
export const INTERFACE = "16001";
const NOTES = "Recorded narration for Lore Forever.";
const FORMAT = 1;

export function renderToc({ title, version, locale, interface: iface, author = null, credit = null, sample = null }) {
  const lines = [`## Interface: ${iface}`, `## Title: ${title}`, `## Notes: ${NOTES}`];
  if (author) lines.push(`## Author: ${author}`);
  lines.push(`## Version: ${version}`, "## Dependencies: LoreForever", "## LoadOnDemand: 1",
             "## X-LoreForever-Pack: voice", `## X-LoreForever-Locale: ${locale}`, `## X-LoreForever-Format: ${FORMAT}`);
  if (credit) lines.push(`## X-LoreForever-Credit: ${credit}`);
  if (sample) lines.push(`## X-LoreForever-Sample: ${sample}`);
  return [...lines, "Clips.lua", ""].join("\n");
}

const luaStr = s => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

// Python sorts the clip ids by code point; so does this for the ids we have (no characters outside the BMP).
export function renderClips(hashes, ext = "mp3") {
  const lines = ["-- Generated by pipeline/lore/voicepack.py - do not edit by hand.",
                 "local name = ...",
                 "local P = LoreForeverPacks and LoreForeverPacks.Begin(name)",
                 "if not P then return end",
                 "local c = P.clips"];
  if (ext !== "mp3") lines.push(`P.ext = ${luaStr(ext)}`);
  const ids = Object.keys(hashes).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const id of ids) lines.push(`c[${luaStr(id)}] = ${luaStr(hashes[id])}`);
  return [...lines, ""].join("\n");
}

// A TOC value on one line, without the game's | escape codes.
const tocValue = s => String(s).replace(/[\x00-\x1f\x7f|]+/g, " ").trim();

// "test-20261001.1830" from the newest recording in the pack, so the same uploads give the same TOC.
function testVersion(created) {
  const d = created.reduce((a, b) => (a > b ? a : b), "");
  const m = d.match(/^(\d{4})-(\d\d)-(\d\d)T(\d\d):(\d\d)/);
  return m ? `test-${m[1]}${m[2]}${m[3]}.${m[4]}${m[5]}` : "test";
}

// R2 sizes under a prefix: {key: size}. One list call per 1000 files.
async function sizes(bucket, prefix) {
  const out = {};
  let cursor;
  do {
    const page = await bucket.list({ prefix, cursor, limit: 1000 });
    for (const o of page.objects) out[o.key] = o.size;
    cursor = page.truncated ? page.cursor : undefined;
  } while (cursor);
  return out;
}

// The test pack for a voice. voice: {id, owner, name, locale}; takes: studio_takes rows (line_id, r2_key, ext, hash,
// crc32, created); index: lineIndex(lines.json). Returns null when nothing can go in, else
// {folder, lines, ext, stream, length}. saveCrc(row, crc) keeps a CRC worked out on the way (uploads from before
// the page sent one).
export async function testPack({ voice, takes, index, bucket, saveCrc = null, when = new Date() }) {
  const byLine = Object.fromEntries(takes.map(t => [t.line_id, t]));
  const current = {};
  for (const [id, l] of Object.entries(index)) if (l.hash[voice.locale]) current[id] = l.hash[voice.locale];
  const plan = planPack(byLine, current);
  const have = await sizes(bucket, `studio/${voice.owner}/${voice.id}/`);
  const rows = plan.lines.map(id => byLine[id]).filter(t => have[t.r2_key] !== undefined);
  if (!rows.length) return null;

  const folder = packFolder(voice.id);
  const ids = rows.map(t => t.line_id);
  const sample = ids.includes("zone:stormwind") ? "zone:stormwind" : ids[0];
  const toc = renderToc({ title: `${tocValue(voice.name) || "My voice"} (test pack)`, version: testVersion(rows.map(t => t.created)),
                          locale: voice.locale, interface: INTERFACE, sample });
  const clips = renderClips(Object.fromEntries(rows.map(t => [t.line_id, current[t.line_id]])), plan.ext);
  const enc = new TextEncoder();
  const entries = [
    { name: `${folder}/${folder}.toc`, data: enc.encode(toc) },
    { name: `${folder}/Clips.lua`, data: enc.encode(clips) },
    ...rows
      .map(t => ({ t, file: `${index[t.line_id].file}.${plan.ext}` }))
      .sort((a, b) => (a.file < b.file ? -1 : 1))
      .map(({ t, file }) => ({
        name: `${folder}/Audio/${file}`,
        size: have[t.r2_key],
        crc: /^[0-9a-f]{8}$/.test(t.crc32 || "") ? parseInt(t.crc32, 16) : null,
        open: async () => {
          const obj = await bucket.get(t.r2_key);
          if (!obj) throw new Error(`${t.r2_key} is gone`);
          return obj.body;
        },
        onCrc: saveCrc ? crc => saveCrc(t, crc) : null,
      })),
  ];
  return { folder, lines: rows.length, ext: plan.ext, stream: zipStream(entries, when), length: zipLength(entries) };
}
